// out/<ID>/script.md: every string the videos show or say, each figure beside the data field it
// comes from, and each built format's voice lines with their time windows. Written by
// scripts/render.mjs after every build; read by the owner at Gate B, by /post-pack and by the
// compliance-reviewer subagent.

import fs from "node:fs";
import path from "node:path";

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");
const field = (id) => (id ? `\`${id}\`` : "our calculation");

export function writeScript(root, id) {
  const buildDir = path.join(root, "out", id, "build");
  const m = JSON.parse(fs.readFileSync(path.join(buildDir, "model.json"), "utf8"));
  const md = [
    `# Script: ${m.company.name} ${m.period_display}`,
    "",
    `Generated by \`scripts/render.mjs\` from \`out/${id}/build/model.json\`, which formats every figure from \`${m.data_file}\` with \`scripts/fmt.py\`. Fields are line or segment ids in that file.`,
    "",
    "## On screen in every format",
    "",
    `- ${m.company.name} (${m.company.ticker}), ${m.period_display}`,
    `- ${m.source_line}`,
    `- ${m.basis_line}. ${m.disclaimer}.`,
    "",
    "## Money map figures",
    "",
    "| On screen | Field | Note |",
    "| --- | --- | --- |",
    ...m.nodes.map((n) => `| ${cell([n.label, n.display, n.change].filter(Boolean).join(" "))}${n.share ? ` (${cell(n.share)})` : ""} | ${field(n.printed)} | ${cell([n.note, n.kind === "loss" ? "loss, hatched" : ""].filter(Boolean).join("; "))} |`),
    "",
    `Hook: "${m.hook.line}" ${m.hook.sub ? `then "${m.hook.sub}"` : ""} (number from \`revenue_total\`).`,
    m.insight ? `Insight: "${m.insight.headline}", "${m.insight.sub}" (from the figures above).` : "Insight: none this quarter.",
    `Call to action: "${m.cta}".`,
    "",
  ];
  const ds = m.formats?.dollar_split;
  if (ds) {
    md.push("## Dollar split figures", "", `Hook: "${ds.hook.replace(/ /g, " ")}" Cents per $1 of revenue are our calculation from the money map figures, rounded so they add to 100.`, "");
    md.push(...ds.parts.map((p) => `- ${p.cents}¢ ${p.label}`), "");
  }
  const kc = m.formats?.kpi_cards;
  if (kc) {
    md.push("## KPI card figures", "", `Hook: "${kc.hook}"`, "", "| Card | On screen | Field |", "| --- | --- | --- |");
    md.push(...kc.cards.map((c) => `| ${cell(c.label)} | ${cell(c.display)} ${cell(c.sub)} | ${field(c.printed)} |`), "");
  }
  for (const format of ["money-map", "dollar-split", "kpi-cards"]) {
    const f = path.join(buildDir, `beats-${format}.json`);
    if (!fs.existsSync(f)) continue;
    const b = JSON.parse(fs.readFileSync(f, "utf8"));
    md.push(`## ${format} voice (${b.duration} s, Kokoro ${b.speed}×)`, "", "| From | To | Beat | Voice |", "| --- | --- | --- | --- |");
    md.push(...b.beats.map((x) => `| ${x.start.toFixed(2)} | ${(x.start + x.dur).toFixed(2)} | ${x.beat} | ${cell(x.text)} |`), "");
  }
  fs.writeFileSync(path.join(root, "out", id, "script.md"), md.join("\n"));
}
